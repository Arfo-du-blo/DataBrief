-- Source of the "Do not share data" canary dumps (SQL text and PostgreSQL archive). Every CONFIDENTIAL_ value must stay out
-- of the prompt unless the user allows it (see tests/make_fixtures.py): REC = a record (never), TEXT = free text, SQL = a
-- literal in a definition, COL = a name (table, column, index, view, TYPE), LABEL = a column comment or an enum label.
CREATE TYPE "CONFIDENTIAL_COL_ENUM" AS ENUM ('CONFIDENTIAL_LABEL_E1', 'CONFIDENTIAL_LABEL_E2');
CREATE TABLE "CONFIDENTIAL_COL_PARENT" ("CONFIDENTIAL_COL_ID" integer PRIMARY KEY, label text);
CREATE TABLE "CONFIDENTIAL_COL_TABLE" (
  "CONFIDENTIAL_COL_A" text DEFAULT 'CONFIDENTIAL_SQL_DEFAULT',
  "CONFIDENTIAL_COL_B" integer,
  "CONFIDENTIAL_COL_C" text,
  "CONFIDENTIAL_COL_PID" integer REFERENCES "CONFIDENTIAL_COL_PARENT" ("CONFIDENTIAL_COL_ID"),
  "CONFIDENTIAL_COL_KIND" "CONFIDENTIAL_COL_ENUM"
);
CREATE INDEX "CONFIDENTIAL_COL_INDEX" ON "CONFIDENTIAL_COL_TABLE" ("CONFIDENTIAL_COL_B");
COMMENT ON TABLE "CONFIDENTIAL_COL_TABLE" IS 'CONFIDENTIAL_TEXT_TABLECOMMENT';
COMMENT ON COLUMN "CONFIDENTIAL_COL_TABLE"."CONFIDENTIAL_COL_A" IS 'CONFIDENTIAL_LABEL_COLCOMMENT';
CREATE VIEW "CONFIDENTIAL_COL_VIEW" AS
  SELECT "CONFIDENTIAL_COL_A" FROM "CONFIDENTIAL_COL_TABLE" WHERE "CONFIDENTIAL_COL_A" = 'CONFIDENTIAL_SQL_LITERAL';
INSERT INTO "CONFIDENTIAL_COL_PARENT" VALUES (1, 'CONFIDENTIAL_REC_PARENT');
INSERT INTO "CONFIDENTIAL_COL_TABLE"
  SELECT 'CONFIDENTIAL_REC_' || lpad(g::text, 2, '0'), 100 + (g - 1) * 3,
         CASE WHEN g <= 8 THEN 'common' WHEN g <= 11 THEN 'other' ELSE 'CONFIDENTIAL_REC_RARE' END,
         1, CASE WHEN g <= 2 THEN 'CONFIDENTIAL_LABEL_E1'::"CONFIDENTIAL_COL_ENUM" END   -- 2 rows only: a group under 5 records is never summarised
  FROM generate_series(1, 12) g;
