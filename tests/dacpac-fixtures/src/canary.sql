-- Canary of the "Do not share data" tests: names (CONFIDENTIAL_COL), literals in definitions (CONFIDENTIAL_SQL), free text (CONFIDENTIAL_TEXT),
-- labels (CONFIDENTIAL_LABEL). A dacpac holds no rows.
CREATE TABLE [dbo].[CONFIDENTIAL_COL_PARENT] ([CONFIDENTIAL_COL_ID] INT NOT NULL PRIMARY KEY, [Label] NVARCHAR(50) NULL);
---
CREATE TABLE [dbo].[CONFIDENTIAL_COL_TABLE] (
  [CONFIDENTIAL_COL_A] NVARCHAR(40) NULL CONSTRAINT [DF_CONFIDENTIAL_COL_A] DEFAULT (N'CONFIDENTIAL_SQL_DEFAULT'),
  [CONFIDENTIAL_COL_B] INT NULL,
  [CONFIDENTIAL_COL_C] NVARCHAR(40) NULL,
  [CONFIDENTIAL_COL_PID] INT NULL,
  CONSTRAINT [FK_CONFIDENTIAL_COL] FOREIGN KEY ([CONFIDENTIAL_COL_PID]) REFERENCES [dbo].[CONFIDENTIAL_COL_PARENT] ([CONFIDENTIAL_COL_ID])
);
---
CREATE INDEX [CONFIDENTIAL_COL_INDEX] ON [dbo].[CONFIDENTIAL_COL_TABLE] ([CONFIDENTIAL_COL_B]);
---
CREATE VIEW [dbo].[CONFIDENTIAL_COL_VIEW] AS SELECT [CONFIDENTIAL_COL_A] FROM [dbo].[CONFIDENTIAL_COL_TABLE] WHERE [CONFIDENTIAL_COL_A] = N'CONFIDENTIAL_SQL_LITERAL';
---
EXEC sp_addextendedproperty @name = N'MS_Description', @value = N'CONFIDENTIAL_TEXT_TABLECOMMENT', @level0type = N'SCHEMA', @level0name = N'dbo', @level1type = N'TABLE', @level1name = N'CONFIDENTIAL_COL_TABLE';
---
EXEC sp_addextendedproperty @name = N'MS_Description', @value = N'CONFIDENTIAL_LABEL_COLCOMMENT', @level0type = N'SCHEMA', @level0name = N'dbo', @level1type = N'TABLE', @level1name = N'CONFIDENTIAL_COL_TABLE', @level2type = N'COLUMN', @level2name = N'CONFIDENTIAL_COL_A';
