#!/usr/bin/env python3
"""
Compresses databrief.html and writes it as a C header for the ESP32 firmware (DataBrief/databrief_html.h).
Python twin of make_header.ps1. See docs/esp32-arduino.md.

  python make_header.py                          uses databrief.html at the repository root
  python make_header.py path/to/databrief.html   e.g. a team version made with databrief_set_default.html
  python make_header.py --with-pdf ...           keep the PDF reader (about 0.5 MB more in the firmware)
  python make_header.py --page-out page.html ... also write the page as embedded (to check it in a browser)

The PDF reader (pdf.js, between the "DataBrief: PDF reader" markers of the page) is left out by default: the page then
answers a PDF with the "recognised but not readable" message, and keeps the firmware small.

PlatformIO runs this file automatically before each build (extra_scripts in platformio.ini).
There, set the environment variable DATABRIEF_HTML to embed another file, DATABRIEF_PDF=1 to keep the PDF reader.
"""
import gzip
import hashlib
import os
import re
import sys

PDF_BLOCK = re.compile(rb"<!-- DataBrief: PDF reader start[^>]*-->.*?<!-- DataBrief: PDF reader end -->\n?", re.S)


def embedded_page(page, with_pdf):
    """The page as the ESP32 serves it: without the PDF reader unless asked."""
    return page if with_pdf else PDF_BLOCK.sub(b"", page, count=1)


def make_header(html_path, out_path, with_pdf=False, page_out=None):
    with open(html_path, "rb") as f:
        source = f.read()
    page = embedded_page(source, with_pdf)
    if page_out:
        with open(page_out, "wb") as f:
            f.write(page)
    data = gzip.compress(page, compresslevel=9, mtime=0)
    lines = [
        "// Generated by deploy/esp32/make_header from databrief.html - do not edit, run the script again instead.",
        "// Source: %d bytes, SHA-256 %s" % (len(source), hashlib.sha256(source).hexdigest()),
        "// Embedded: %d bytes, gzip-compressed (the browser decompresses it); PDF option: %s." % (len(data), "with the PDF reader" if with_pdf else "without the PDF reader"),
        "#pragma once",
        "#include <Arduino.h>",
        "",
        'static const char DATABRIEF_HTML_SHA256[] = "%s";' % hashlib.sha256(page).hexdigest(),
        "static const size_t DATABRIEF_HTML_GZ_LEN = %d;" % len(data),
        "static const uint8_t DATABRIEF_HTML_GZ[] PROGMEM = {",
    ]
    for i in range(0, len(data), 32):
        lines.append("".join("0x%02x," % b for b in data[i:i + 32]))
    lines.append("};")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("Built %s (page %.2f MB -> %.2f MB compressed%s)" % (out_path, len(page) / 2**20, len(data) / 2**20,
                                                               ", with the PDF reader" if with_pdf else ", without the PDF reader"))


def paths(esp32_dir, html=None):
    html = html or os.environ.get("DATABRIEF_HTML") or os.path.join(esp32_dir, "..", "..", "databrief.html")
    return os.path.abspath(html), os.path.join(esp32_dir, "DataBrief", "databrief_html.h")


if __name__ == "__main__":
    args = sys.argv[1:]
    with_pdf = "--with-pdf" in args
    page_out = None
    if "--page-out" in args:
        i = args.index("--page-out")
        page_out = args[i + 1]
        del args[i:i + 2]
    args = [a for a in args if a != "--with-pdf"]
    html_path, out_path = paths(os.path.dirname(os.path.abspath(__file__)), args[0] if args else None)
    make_header(html_path, out_path, with_pdf, page_out)
else:
    # Run by PlatformIO (SCons): "env" and the project folder come from the build system.
    try:
        Import("env")  # noqa: F821  (provided by PlatformIO)
        html_path, out_path = paths(env.subst("$PROJECT_DIR"))  # noqa: F821
        if not os.path.exists(html_path):
            sys.exit("DataBrief: %s not found (set DATABRIEF_HTML to your databrief.html)" % html_path)
        with_pdf = os.environ.get("DATABRIEF_PDF", "") == "1"
        # Rebuild only when the page or the PDF choice changed (the header records the SHA-256 of its source page)
        with open(html_path, "rb") as f:
            sha = hashlib.sha256(f.read()).hexdigest()
        current = ""
        if os.path.exists(out_path):
            with open(out_path, encoding="utf-8") as f:
                current = f.read(600)
        wanted = "PDF option: %s" % ("with the PDF reader" if with_pdf else "without the PDF reader")   # the option asked, not what the page held
        if sha not in current or wanted not in current:
            make_header(html_path, out_path, with_pdf)
    except NameError:
        pass
