<#
.SYNOPSIS
  Compresses databrief.html and writes it as a C header for the ESP32 firmware (DataBrief/databrief_html.h).

.DESCRIPTION
  The ESP32 stores the page gzip-compressed (about 1.2 MB instead of 3.3 MB) inside the firmware and sends it
  as is: the browser decompresses it. Run this script again whenever databrief.html changes, for example after
  making a team version with databrief_set_default.html. build.ps1 runs it automatically, and PlatformIO runs
  the Python twin (make_header.py) before each build.
  The PDF reader (pdf.js, between the "DataBrief: PDF reader" markers of the page) is left out by default: the
  page then answers a PDF with the "recognised but not readable" message, and the firmware stays small.
  See docs/esp32-arduino.md.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File deploy\esp32\make_header.ps1
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File deploy\esp32\make_header.ps1 -Html C:\Users\me\Downloads\databrief.html
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File deploy\esp32\make_header.ps1 -WithPdf
#>
param(
  # The page to embed (default: databrief.html at the repository root).
  [string]$Html = (Join-Path $PSScriptRoot '..\..\databrief.html'),
  # The header to write (default: next to the sketch).
  [string]$Out = (Join-Path $PSScriptRoot 'DataBrief\databrief_html.h'),
  # Keep the PDF reader (about 0.5 MB more in the firmware).
  [switch]$WithPdf,
  # Also write the page as embedded (to check it in a browser).
  [string]$PageOut = ''
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression

$Html = (Resolve-Path $Html).Path
$source = [System.IO.File]::ReadAllBytes($Html)
$sha256 = [System.Security.Cryptography.SHA256]::Create()
$hex = { param($b) -join ($sha256.ComputeHash($b) | ForEach-Object { $_.ToString('x2') }) }
$sourceSha = & $hex $source

# The page as the ESP32 serves it: without the PDF reader unless asked (bytes kept as they are: Latin-1 maps them 1:1)
$latin1 = [System.Text.Encoding]::GetEncoding(28591)
$text = $latin1.GetString($source)
$pdfLeftOut = $false
if (-not $WithPdf) {
  $m = [regex]::Match($text, '<!-- DataBrief: PDF reader start[^>]*-->[\s\S]*?<!-- DataBrief: PDF reader end -->\n?')
  if ($m.Success) { $text = $text.Remove($m.Index, $m.Length); $pdfLeftOut = $true }
}
$bytes = $latin1.GetBytes($text)
if ($PageOut) { [System.IO.File]::WriteAllBytes([System.IO.Path]::GetFullPath($PageOut), $bytes) }
$sha = & $hex $bytes

$ms = New-Object System.IO.MemoryStream
$gz = New-Object System.IO.Compression.GZipStream($ms, [System.IO.Compression.CompressionLevel]::Optimal)
$gz.Write($bytes, 0, $bytes.Length)
$gz.Close()
$data = $ms.ToArray()

$sb = New-Object System.Text.StringBuilder ($data.Length * 5 + 1024)
[void]$sb.Append("// Generated by deploy/esp32/make_header from databrief.html - do not edit, run the script again instead.`n")
[void]$sb.Append("// Source: $($source.Length) bytes, SHA-256 $sourceSha`n")
[void]$sb.Append("// Embedded: $($data.Length) bytes, gzip-compressed (the browser decompresses it); PDF reader: $(if ($pdfLeftOut) { 'left out' } else { 'kept' }).`n")
[void]$sb.Append("#pragma once`n#include <Arduino.h>`n`n")
[void]$sb.Append("static const char DATABRIEF_HTML_SHA256[] = `"$sha`";`n")
[void]$sb.Append("static const size_t DATABRIEF_HTML_GZ_LEN = $($data.Length);`n")
[void]$sb.Append("static const uint8_t DATABRIEF_HTML_GZ[] PROGMEM = {`n")
for ($i = 0; $i -lt $data.Length; $i++) {
  [void]$sb.Append('0x').Append($data[$i].ToString('x2')).Append(',')
  if (($i % 32) -eq 31) { [void]$sb.Append("`n") }
}
[void]$sb.Append("`n};`n")

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($Out), $sb.ToString(), $utf8)
Write-Output ("Built {0} (page {1:N2} MB -> {2:N2} MB compressed{3})" -f $Out, ($bytes.Length / 1MB), ($data.Length / 1MB), $(if ($pdfLeftOut) { ', without the PDF reader' } else { '' }))
