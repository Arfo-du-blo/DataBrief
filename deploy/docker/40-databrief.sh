#!/bin/sh
# DataBrief - runs at every start of the nginx image (before nginx).
# Writes the DATABRIEF_* settings into the page and generates the nginx configuration.
set -eu

PORT="${DATABRIEF_PORT:-8080}"
BASE="${DATABRIEF_BASE_PATH:-/}"
case "$BASE" in /*) ;; *) BASE="/$BASE" ;; esac
case "$BASE" in */) ;; *) BASE="$BASE/" ;; esac
FRAME="${DATABRIEF_FRAME_ANCESTORS:-'self'}"
MAXCONN="${DATABRIEF_MAX_CONNECTIONS:-1024}"
case "$PORT$MAXCONN" in *[!0-9]*) echo "DataBrief: DATABRIEF_PORT and DATABRIEF_MAX_CONNECTIONS must be numbers" >&2; exit 1 ;; esac

# ---- page settings -> JSON config block (only values that differ from the built-in defaults)
# -s: read the whole value as one string, so an empty DATABRIEF_LOCK gives [] (without -s, jq outputs nothing).
LOCK_JSON=$(printf '%s' "${DATABRIEF_LOCK:-}" | jq -R -s -c 'split(",") | map(gsub("^\\s+|\\s+$"; "")) | map(select(length > 0))')
# jq writes to a file first: in a pipe, a jq error would go unnoticed (set -e only sees the last command).
jq -n \
  --arg lang "${DATABRIEF_LANG:-}" \
  --arg promptLang "${DATABRIEF_PROMPT_LANG:-}" \
  --arg mode "${DATABRIEF_MODE:-}" \
  --arg layout "${DATABRIEF_LAYOUT:-}" \
  --arg theme "${DATABRIEF_THEME:-}" \
  --arg sample "${DATABRIEF_SAMPLE_ROWS:-}" \
  --arg warn "${DATABRIEF_WARN_TOKENS:-}" \
  --arg intro "${DATABRIEF_PROMPT_INTRO:-}" \
  --arg respond "${DATABRIEF_PROMPT_RESPOND:-}" \
  --arg respondFiles "${DATABRIEF_PROMPT_RESPOND_FILES:-}" \
  --argjson lock "$LOCK_JSON" '
  def set(k; v; skip): if v != "" and v != skip then {(k): v} else {} end;
  set("lang"; $lang; "") + set("promptLang"; $promptLang; "") + set("mode"; $mode; "inline")
  + set("layout"; $layout; "auto") + set("theme"; $theme; "system")
  + (if $sample != "" and $sample != "5" then {sampleRows: ($sample | tonumber)} else {} end)
  + (if $warn != "" and $warn != "150000" then {warnTokens: ($warn | tonumber)} else {} end)
  + (if ($lock | length) > 0 then {lock: $lock} else {} end)
  + set("promptIntro"; $intro; "") + set("promptRespond"; $respond; "") + set("promptRespondFiles"; $respondFiles; "")
' > /tmp/databrief-config.raw.json
sed 's/</\\u003c/g' /tmp/databrief-config.raw.json > /tmp/databrief-config.json

awk -v cfg=/tmp/databrief-config.json '
  /<script id="databrief-config" type="application\/json">/ { print; while ((getline line < cfg) > 0) print line; skip = 1; next }
  skip && /<\/script>/ { skip = 0 }
  !skip { print }
' /opt/databrief/databrief.html > /var/www/databrief/index.html

# ---- nginx configuration
sed -i "s/worker_connections .*;/worker_connections ${MAXCONN};/" /etc/nginx/nginx.conf
case "${DATABRIEF_ACCESS_LOG:-true}" in true|1|yes) ACCESS="access_log /dev/stdout;" ;; *) ACCESS="access_log off;" ;; esac
REDIRECT=""
if [ "$BASE" != "/" ]; then REDIRECT="location = ${BASE%/} { return 301 ${BASE}; }"; fi

cat > /etc/nginx/conf.d/default.conf <<EOF
# Generated by DataBrief at container start - edit the DATABRIEF_* variables instead.
server {
    listen ${PORT};
    server_tokens off;
    root /var/www/databrief;
    ${ACCESS}

    gzip on;
    gzip_comp_level 6;
    gzip_types text/html text/plain;

    add_header Content-Security-Policy "frame-ancestors ${FRAME}" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "no-referrer" always;

    location = /healthz { access_log off; default_type text/plain; return 200 "ok\n"; }
    ${REDIRECT}
    location = ${BASE} { add_header Cache-Control "no-cache" always; add_header Content-Security-Policy "frame-ancestors ${FRAME}" always; add_header X-Content-Type-Options "nosniff" always; add_header Referrer-Policy "no-referrer" always; default_type text/html; try_files /index.html =404; }
    location = ${BASE}index.html { default_type text/html; try_files /index.html =404; }
    location = ${BASE}databrief.html { default_type text/html; try_files /index.html =404; }
    location / { return 404; }
}
EOF
echo "DataBrief: settings written, serving http://localhost:${PORT}${BASE}"
